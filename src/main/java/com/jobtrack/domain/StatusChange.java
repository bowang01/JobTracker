package com.jobtrack.domain;

import java.time.LocalDateTime;
import java.util.UUID;

import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

/** One status change. Append-only once written (audit trail). */
@Entity
@Table(name = "status_history")
public class StatusChange {

    /** Random UUID generated by Hibernate before insert; stored as CHAR(36). */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @JdbcTypeCode(SqlTypes.CHAR)
    @Column(length = 36, nullable = false, updatable = false)
    private UUID id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "application_id", nullable = false, updatable = false)
    private JobApplication application;

    @Enumerated(EnumType.STRING)
    @Column(name = "from_status", length = 30, updatable = false)
    private ApplicationStatus fromStatus;

    @Enumerated(EnumType.STRING)
    @Column(name = "to_status", nullable = false, length = 30, updatable = false)
    private ApplicationStatus toStatus;

    /** When the event actually happened (may be in the past when backfilling). */
    @Column(name = "occurred_at", nullable = false, updatable = false)
    private LocalDateTime occurredAt;

    /** When the record was entered into the system. */
    @Column(name = "recorded_at", nullable = false, updatable = false)
    private LocalDateTime recordedAt;

    @Column(length = 1000, updatable = false)
    private String note;

    @ManyToOne(fetch = FetchType.LAZY)
    @JoinColumn(name = "changed_by", updatable = false)
    private User changedBy;

    protected StatusChange() {
    }

    public StatusChange(JobApplication application, ApplicationStatus fromStatus, ApplicationStatus toStatus,
                        LocalDateTime occurredAt, LocalDateTime recordedAt, String note, User changedBy) {
        this.application = application;
        this.fromStatus = fromStatus;
        this.toStatus = toStatus;
        this.occurredAt = occurredAt;
        this.recordedAt = recordedAt;
        this.note = note;
        this.changedBy = changedBy;
    }

    /** Treated as backfilled when it was recorded more than an hour after it happened. */
    public boolean isBackfilled() {
        return recordedAt.isAfter(occurredAt.plusHours(1));
    }

    public UUID getId() {
        return id;
    }

    public JobApplication getApplication() {
        return application;
    }

    public ApplicationStatus getFromStatus() {
        return fromStatus;
    }

    public ApplicationStatus getToStatus() {
        return toStatus;
    }

    public LocalDateTime getOccurredAt() {
        return occurredAt;
    }

    public LocalDateTime getRecordedAt() {
        return recordedAt;
    }

    public String getNote() {
        return note;
    }

    public User getChangedBy() {
        return changedBy;
    }
}
