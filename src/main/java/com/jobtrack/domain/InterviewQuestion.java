package com.jobtrack.domain;

import java.time.LocalDateTime;
import java.util.UUID;

import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.PrePersist;
import jakarta.persistence.PreUpdate;
import jakarta.persistence.Table;

/** One question in a user's interview question bank, with their answer and self-assessment. Not tied to any application. */
@Entity
@Table(name = "interview_questions")
public class InterviewQuestion {

    /** Random UUID generated by Hibernate before insert; stored as CHAR(36). */
    @Id
    @GeneratedValue(strategy = GenerationType.UUID)
    @JdbcTypeCode(SqlTypes.CHAR)
    @Column(length = 36, nullable = false, updatable = false)
    private UUID id;

    /** Owner; never changes after creation. */
    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false, updatable = false)
    private User owner;

    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 20)
    private QuestionCategory category;

    @Column(name = "question_text", nullable = false, length = 5000)
    private String questionText;

    /** How the user answered, or a better answer worked out afterwards. */
    @Column(name = "answer_text", length = 10000)
    private String answerText;

    @Enumerated(EnumType.STRING)
    @Column(name = "self_rating", length = 10)
    private AnswerRating selfRating;

    /** PRIVATE by default. PUBLIC questions appear in the interview hall (without the answer or rating). */
    @Enumerated(EnumType.STRING)
    @Column(nullable = false, length = 10)
    private Visibility visibility = Visibility.PRIVATE;

    /** When the question was (last) made public; null while private. */
    @Column(name = "published_at")
    private LocalDateTime publishedAt;

    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;

    @Column(name = "updated_at", nullable = false)
    private LocalDateTime updatedAt;

    @PrePersist
    void prePersist() {
        LocalDateTime now = LocalDateTime.now();
        if (createdAt == null) {
            createdAt = now;
        }
        updatedAt = now;
    }

    @PreUpdate
    void preUpdate() {
        updatedAt = LocalDateTime.now();
    }

    public UUID getId() {
        return id;
    }

    public User getOwner() {
        return owner;
    }

    public void setOwner(User owner) {
        if (this.owner != null) {
            throw new IllegalStateException("The owner of a question cannot be changed");
        }
        this.owner = owner;
    }

    public QuestionCategory getCategory() {
        return category;
    }

    public void setCategory(QuestionCategory category) {
        this.category = category;
    }

    public String getQuestionText() {
        return questionText;
    }

    public void setQuestionText(String questionText) {
        this.questionText = questionText;
    }

    public String getAnswerText() {
        return answerText;
    }

    public void setAnswerText(String answerText) {
        this.answerText = answerText;
    }

    public AnswerRating getSelfRating() {
        return selfRating;
    }

    public void setSelfRating(AnswerRating selfRating) {
        this.selfRating = selfRating;
    }

    public Visibility getVisibility() {
        return visibility;
    }

    public boolean isPublic() {
        return visibility == Visibility.PUBLIC;
    }

    /** Changes visibility and keeps publishedAt consistent with it. */
    public void changeVisibility(Visibility newVisibility, LocalDateTime now) {
        Visibility target = newVisibility == null ? Visibility.PRIVATE : newVisibility;
        if (target == Visibility.PUBLIC && visibility != Visibility.PUBLIC) {
            publishedAt = now;
        } else if (target == Visibility.PRIVATE) {
            publishedAt = null;
        }
        visibility = target;
    }

    public LocalDateTime getPublishedAt() {
        return publishedAt;
    }

    public LocalDateTime getCreatedAt() {
        return createdAt;
    }

    public LocalDateTime getUpdatedAt() {
        return updatedAt;
    }
}
